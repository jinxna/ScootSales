import 'package:flutter/material.dart';

import '../app/build_flags.dart';
import '../utils/ai_data_freshness.dart';

class AiFreshnessChip extends StatelessWidget {
  const AiFreshnessChip({
    super.key,
    required this.hasData,
    required this.timestamps,
    this.hasMissingTimestamp = false,
    this.now,
  });

  final bool hasData;
  final Iterable<DateTime?> timestamps;
  final bool hasMissingTimestamp;

  final DateTime? now;

  @override
  Widget build(BuildContext context) {
    if (isBasicEdition) return const SizedBox.shrink();
    final DateTime currentTime = now ?? DateTime.now();
    final AiDataFreshness freshness = calculateAiDataFreshness(
      hasData: hasData,
      timestamps: timestamps,
      now: currentTime,
      hasMissingTimestamp: hasMissingTimestamp,
    );
    final bool stale = freshness.state == AiFreshnessState.stale;
    final bool unavailable =
        freshness.state == AiFreshnessState.timestampUnavailable;
    final ColorScheme colors = Theme.of(context).colorScheme;
    final Color foreground = stale
        ? const Color(0xFF8A4B00)
        : unavailable
        ? colors.onSurfaceVariant
        : colors.onSurfaceVariant;
    final Color background = stale
        ? const Color(0xFFFFF1D6)
        : colors.surfaceContainerHighest;

    return Tooltip(
      message: stale
          ? 'The newest available AI data is more than 7 days old.'
          : freshness.state == AiFreshnessState.noData
          ? 'No generated AI data is available.'
          : 'These insights are generated by the weekly update and read from saved data.',
      child: Semantics(
        label: aiFreshnessMessage(freshness, now: currentTime),
        child: Container(
          constraints: const BoxConstraints(maxWidth: 360),
          padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 6),
          decoration: BoxDecoration(
            color: background,
            borderRadius: BorderRadius.circular(20),
            border: Border.all(
              color: stale ? const Color(0xFFE0A43A) : colors.outlineVariant,
            ),
          ),
          child: Row(
            mainAxisSize: MainAxisSize.min,
            children: <Widget>[
              Icon(
                stale
                    ? Icons.warning_amber_rounded
                    : unavailable
                    ? Icons.schedule_rounded
                    : Icons.event_repeat_outlined,
                size: 15,
                color: foreground,
              ),
              const SizedBox(width: 6),
              Flexible(
                child: Text(
                  aiFreshnessMessage(freshness, now: currentTime),
                  overflow: TextOverflow.ellipsis,
                  style: Theme.of(context).textTheme.labelSmall?.copyWith(
                    color: foreground,
                    fontWeight: FontWeight.w600,
                  ),
                ),
              ),
              if (stale) ...<Widget>[
                const SizedBox(width: 6),
                const Text(
                  'Stale',
                  style: TextStyle(
                    color: Color(0xFF8A4B00),
                    fontSize: 11,
                    fontWeight: FontWeight.w700,
                  ),
                ),
              ],
            ],
          ),
        ),
      ),
    );
  }
}
